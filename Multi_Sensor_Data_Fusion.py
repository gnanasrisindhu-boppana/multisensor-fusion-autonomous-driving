class ReplayBuf:
    def __init__(s,c=50000): s.b=deque(maxlen=c)
    def push(s,*a): s.b.append(a)
    def sample(s,n): b=random.sample(s.b,n); return [np.array(x) for x in zip(*b)]
    def __len__(s): return len(s.b)

class SpoofAttack:
    def __init__(s,N,sf=.3,ef=.7,off=(5.,2.5,0.),ramp=.1,jit=.3,seed=0):
        s.s=int(N*sf); s.e=int(N*ef); s.mx=np.array(off); s.rf=ramp; s.jit=jit; s.rng=np.random.RandomState(seed)
    def apply(s,k,gps):
        if k<s.s or k>s.e: return False,gps.copy()
        w=s.e-s.s; rl=max(1,int(w*s.rf)); p=k-s.s
        if p<rl: sc=p/rl
        elif p>w-rl: sc=(w-p)/rl
        else: sc=1.
        return True,gps+s.mx*sc+s.rng.randn(3)*s.jit*sc

class FilterEnv:
    def __init__(s,sd,FC,spoof_prob=0.):
        s.sd=sd.reset_index(drop=True); s.n=len(s.sd); s.FC=FC; s.sp_prob=spoof_prob
    def reset(s):
        s.i=0; s.pnis=0.; s.pa=np.zeros(3); s.filt=s.FC()
        r=s.sd.iloc[0]; s.filt.state=np.array([r['gps_x'],r['gps_y'],r['gps_z'],0,0,0],dtype=float)
        s.spoof=SpoofAttack(s.n,seed=np.random.randint(10000)) if np.random.rand()<s.sp_prob else None
        s.log=[]; return s._obs(False)
    def _obs(s,att):
        r=s.sd.iloc[s.i]; st=s.filt.get_state()
        return np.clip(np.array([st[0]-r['gps_x'],st[1]-r['gps_y'],st[3]-r['vx'],st[4]-r['vy'],
            s.pnis,r['ax'],r['ay'],r['radar_vel_mean'],r['radar_count'],
            np.sqrt(r['vx']**2+r['vy']**2),float(att)],dtype=np.float32),-100,100)
    def step(s,action):
        action=np.clip(action,-1,1); sc=0.15+(action+1)*2.925; s.filt.set_noise(*sc)
        s.i+=1
        if s.i>=s.n: return np.zeros(11,np.float32),0.,True,{}
        r=s.sd.iloc[s.i]; s.filt.predict(r['ax'],r['ay'],r['az'],r['dt'])
        z=np.array([r['gps_x'],r['gps_y'],r['gps_z']],dtype=float); att=False
        if s.spoof: att,z=s.spoof.apply(s.i,z)
        _,nis=s.filt.update_gps(z); s.pnis=nis
        zr=radar_vel_meas(r,s.filt.get_state())
        if zr is not None: s.filt.update_radar(zr)
        st=s.filt.get_state()
        pe=np.sqrt((st[0]-r['gps_x'])**2+(st[1]-r['gps_y'])**2)
        ve=np.sqrt((st[3]-r['vx'])**2+(st[4]-r['vy'])**2)
        rew=-pe-.4*ve+(.5 if nis<7.815 else 0)-.03*float(np.sum((action-s.pa)**2))
        s.pa=action.copy(); s.log.append(dict(step=s.i,nis=nis,attacked=att,pos_err=pe))
        return s._obs(att),rew,s.i>=s.n-1,{'pos_err':pe,'vel_err':ve,'nis':nis,'attacked':att}

