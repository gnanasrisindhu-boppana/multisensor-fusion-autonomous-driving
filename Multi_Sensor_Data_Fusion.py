class PPOAgent:
    def __init__(s,sd,ad=3,lr=3e-4,g=.99,gae=.95,cl=.2,ep=10):
        s.dv=torch.device('cuda' if torch.cuda.is_available() else 'cpu'); s.ad=ad
        s.net=PPONet(sd,ad).to(s.dv); s.opt=optim.Adam(s.net.parameters(),lr=lr)
        s.g=g; s.gae=gae; s.cl=cl; s.ep=ep; s._r()
    def _r(s): s.S,s.A,s.R,s.LP,s.V,s.D=[],[],[],[],[],[]
    def act(s,st,ev=False):
        t=torch.FloatTensor(st).unsqueeze(0).to(s.dv); m,l,v=s.net(t)
        if ev: return m.detach().cpu().numpy()[0]
        std=l.exp().clamp(.01,1.); d=torch.distributions.Normal(m,std); a=d.sample().clamp(-1,1)
        s.LP.append(d.log_prob(a).sum(-1).detach().cpu()); s.V.append(v.item())
        return a.detach().cpu().numpy()[0]
    def store(s,st,a,r,d): s.S.append(st); s.A.append(a); s.R.append(r); s.D.append(d)
    def update(s):
        if len(s.S)<32: return
        vs=s.V+[0.]; adv=[]; ret=[]; ga=0
        for t in reversed(range(len(s.R))): d=s.R[t]+s.g*vs[t+1]*(1-s.D[t])-vs[t]; ga=d+s.g*s.gae*(1-s.D[t])*ga; adv.insert(0,ga); ret.insert(0,ga+vs[t])
        st=torch.FloatTensor(np.array(s.S)).to(s.dv); at=torch.FloatTensor(np.array(s.A)).to(s.dv)
        olp=torch.stack(s.LP).to(s.dv); advt=torch.FloatTensor(adv).to(s.dv); rett=torch.FloatTensor(ret).to(s.dv)
        if len(advt)>1: advt=(advt-advt.mean())/(advt.std()+1e-8)
        N=len(st); mb=max(1,N//4)
        for _ in range(s.ep):
            idx=torch.randperm(N)
            for start in range(0,N,mb):
                b=idx[start:start+mb]; m,l,vp=s.net(st[b]); std=l.exp().clamp(.01,1.)
                d=torch.distributions.Normal(m,std); nlp=d.log_prob(at[b]).sum(-1)
                r=(nlp-olp[b]).exp()
                loss=-torch.min(r*advt[b],torch.clamp(r,1-s.cl,1+s.cl)*advt[b]).mean()+.5*TF.mse_loss(vp.squeeze(-1),rett[b])-.01*d.entropy().sum(-1).mean()
                s.opt.zero_grad(); loss.backward(); nn.utils.clip_grad_norm_(s.net.parameters(),.5); s.opt.step()
        s._r()

# Ensemble
class EnsembleAgent:
    def __init__(s,agents): s.agents=agents
    def act(s,state,ev=True): return np.median([a.act(state,ev=ev) for _,a in s.agents],axis=0)

