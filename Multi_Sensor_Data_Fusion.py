def radar_vel_meas(row,filt_state):
    vx,vy=filt_state[3],filt_state[4]; h=np.arctan2(vy,vx+1e-8)
    if np.sqrt(vx**2+vy**2)<1e-3: h=np.arctan2(row['vy'],row['vx']+1e-8)
    if row['radar_vel_mean']==0: return None
    sp=abs(row['radar_vel_mean']); return np.array([sp*np.cos(h),sp*np.sin(h)])

def run_filter(FC,sd,spoof=None):
    f=FC(); r0=sd.iloc[0]; f.state=np.array([r0['gps_x'],r0['gps_y'],r0['gps_z'],0,0,0],dtype=float)
    ests,niss,errs,verrs,att_flags=[f.get_state()],[0.],[0.],[0.],[False]
    for k in range(1,len(sd)):
        r=sd.iloc[k]; f.predict(r['ax'],r['ay'],r['az'],r['dt'])
        z=np.array([r['gps_x'],r['gps_y'],r['gps_z']]); attacked=False
        if spoof: attacked,z=spoof.apply(k,z)
        _,nis=f.update_gps(z); niss.append(nis)
        zr=radar_vel_meas(r,f.get_state())
        if zr is not None: f.update_radar(zr)
        st=f.get_state(); ests.append(st); att_flags.append(attacked)
        errs.append(np.sqrt((st[0]-r['gps_x'])**2+(st[1]-r['gps_y'])**2))
        verrs.append(np.sqrt((st[3]-r['vx'])**2+(st[4]-r['vy'])**2))
    return dict(estimates=np.array(ests),ground_truth=sd[['gps_x','gps_y','gps_z']].values,
                nis=np.array(niss),errors=np.array(errs),vel_errors=np.array(verrs),
                attacked=att_flags,scene_name=sd['scene_name'].iloc[0])

