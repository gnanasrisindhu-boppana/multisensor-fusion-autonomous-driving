def compute_features(df):
    rows=[]
    for i in range(len(df)-WINDOW+1):
        w=df.iloc[i:i+WINDOW]; r={}
        for col in ['ax','ay','az','gyro_x','gyro_y','gyro_z']:
            r[f'imu_{col}_mean']=w[col].mean(); r[f'imu_{col}_std']=w[col].std()
            r[f'imu_{col}_max']=w[col].max(); r[f'imu_{col}_min']=w[col].min()
            r[f'imu_{col}_range']=w[col].max()-w[col].min()
        am=np.sqrt(w['ax']**2+w['ay']**2+w['az']**2); gm=np.sqrt(w['gyro_x']**2+w['gyro_y']**2+w['gyro_z']**2)
        r['imu_acc_mag_mean']=am.mean(); r['imu_acc_mag_std']=am.std()
        r['imu_gyro_mag_mean']=gm.mean(); r['imu_gyro_mag_std']=gm.std()
        for col in ['vx','vy','vz']: r[f'gps_{col}_mean']=w[col].mean(); r[f'gps_{col}_std']=w[col].std()
        sp=np.sqrt(w['vx']**2+w['vy']**2); r['gps_speed_mean']=sp.mean(); r['gps_speed_std']=sp.std()
        r['gps_dx']=w['gps_x'].iloc[-1]-w['gps_x'].iloc[0]; r['gps_dy']=w['gps_y'].iloc[-1]-w['gps_y'].iloc[0]
        r['gps_displacement']=np.sqrt(r['gps_dx']**2+r['gps_dy']**2)
        h=np.arctan2(w['vy'].values,w['vx'].values+1e-8); r['gps_heading_change']=np.abs(h[-1]-h[0])
        pl=np.sum(np.sqrt(np.diff(w['gps_x'])**2+np.diff(w['gps_y'])**2))
        r['gps_tortuosity']=pl/(r['gps_displacement']+1e-8)
        r['gps_curvature_proxy']=r['gps_heading_change']/(pl+1e-8)
        r['gps_stop_ratio']=np.mean(sp<0.75)
        for col in ['radar_range_mean','radar_range_std','radar_vel_mean','radar_vel_std','radar_rcs_mean','radar_rcs_std','radar_count']:
            r[f'{col}_w_mean']=w[col].mean(); r[f'{col}_w_std']=w[col].std()
        r['radar_motion_ratio']=np.mean(np.abs(w['radar_vel_mean'])>0.5)
        r['radar_density']=np.mean(w['radar_count']); r['radar_energy']=np.mean(w['radar_vel_mean']**2)
        r['scene_id']=w['scene_id'].iloc[0]; mid=WINDOW//2
        r['gt_x']=w['gps_x'].iloc[mid]; r['gt_y']=w['gps_y'].iloc[mid]; r['gt_z']=w['gps_z'].iloc[mid]
        r['gt_vx']=w['vx'].iloc[mid]; r['gt_vy']=w['vy'].iloc[mid]
        rows.append(r)
    return pd.DataFrame(rows)

