class HopfieldNetwork:
    def __init__(s,n=25): s.n=n; s.weights=np.zeros((n,n)); s.stored_patterns={}
    def train(s,pats):
        s.stored_patterns=pats; s.weights=np.zeros((s.n,s.n))
        for p in pats.values(): f=p.flatten(); s.weights+=np.outer(f,f)
        np.fill_diagonal(s.weights,0); s.weights/=len(pats)
    def recall(s,inp,it=20):
        st=inp.flatten().copy()
        for _ in range(it):
            prev=st.copy()
            for i in range(s.n): st[i]=1 if np.dot(s.weights[i],st)>=0 else -1
            if np.array_equal(st,prev): break
        return st
    def classify(s,inp):
        r=s.recall(inp); bl,bs=None,-np.inf
        for l,p in s.stored_patterns.items():
            d=np.linalg.norm(r-p.flatten()); sim=1./(1.+d)
            if sim>bs: bs,bl=sim,l
        return bl,bs

def binarize_features(f,t=None):
    if t is None: t=np.median(f)
    return np.where(f>=t,1,-1)

