class BaseKF:
    Q0=np.diag([.08,.08,.04,.4,.4,.15]); Rg0=np.diag([1.,1.,.5]); Rr0=np.diag([2.5,2.5])
    def __init__(s): s.state=np.zeros(6); s._P=np.eye(6)*10.; s.Q=s.Q0.copy(); s.R_gps=s.Rg0.copy(); s.R_radar=s.Rr0.copy()
    def set_noise(s,qs=1.,rgs=1.,rrs=1.): s.Q=s.Q0*max(float(qs),1e-4); s.R_gps=s.Rg0*max(float(rgs),1e-4); s.R_radar=s.Rr0*max(float(rrs),1e-4)
    def get_state(s): return s.state.copy()
    @staticmethod
    def _kin(x,ax,ay,az,dt): return np.array([x[0]+x[3]*dt+.5*ax*dt*dt,x[1]+x[4]*dt+.5*ay*dt*dt,x[2]+x[5]*dt+.5*az*dt*dt,x[3]+ax*dt,x[4]+ay*dt,x[5]+az*dt])
    @staticmethod
    def _rpd(M,e=1e-8): M=.5*(M+M.T); w,V=np.linalg.eigh(M); return (V*np.maximum(w,e))@V.T
    @staticmethod
    def _sch(M):
        M=.5*(M+M.T)
        try: return np.linalg.cholesky(M)
        except: return np.linalg.cholesky(BaseKF._rpd(M)+np.eye(len(M))*1e-6)

class EKF(BaseKF):
    def predict(s,ax,ay,az,dt):
        s.state=s._kin(s.state,ax,ay,az,dt); F=np.eye(6); F[0,3]=F[1,4]=F[2,5]=dt
        s._P=F@s._P@F.T+s.Q; s._P=.5*(s._P+s._P.T); return s.get_state()
    def _upd(s,z,H,R):
        inn=z-H@s.state; S=H@s._P@H.T+R; Si=np.linalg.inv(S); K=s._P@H.T@Si
        s.state+=K@inn; I_=np.eye(6)-K@H; s._P=I_@s._P@I_.T+K@R@K.T; s._P=.5*(s._P+s._P.T)
        return s.get_state(),float(inn@Si@inn)
    def update_gps(s,z): H=np.zeros((3,6)); H[0,0]=H[1,1]=H[2,2]=1.; return s._upd(z,H,s.R_gps)
    def update_radar(s,z): H=np.zeros((2,6)); H[0,3]=H[1,4]=1.; return s._upd(z,H,s.R_radar)

class UKF(BaseKF):
    def _init__(s,a=1e-3,b=2.,k=0.):
        super().__init__(); n=6; s.lam=a*a*(n+k)-n
        s.Wm=np.full(13,1./(2*(n+s.lam))); s.Wc=s.Wm.copy()
        s.Wm[0]=s.lam/(n+s.lam); s.Wc[0]=s.Wm[0]+(1-a*a+b); s._sc=np.sqrt(n+s.lam)
    def _sig(s):
        S=s._sch(s._P); X=np.zeros((13,6)); X[0]=s.state
        for i in range(6): X[i+1]=s.state+s._sc*S[:,i]; X[7+i]=s.state-s._sc*S[:,i]
        return X
    def predict(s,ax,ay,az,dt):
        X=s._sig(); Xp=np.array([s._kin(x,ax,ay,az,dt) for x in X])
        s.state=s.Wm@Xp; d=Xp-s.state; s._P=(d.T*s.Wc)@d+s.Q; s._P=s._rpd(s._P); return s.get_state()
    def _upd(s,z,idx,R):
        X=s._sig(); Z=X[:,idx]; zp=s.Wm@Z; dz=Z-zp; dx=X-s.state
        S=(dz.T*s.Wc)@dz+R; Cr=(dx.T*s.Wc)@dz; Si=np.linalg.inv(S); K=Cr@Si
        inn=z-zp; s.state+=K@inn; s._P-=K@S@K.T; s._P=s._rpd(s._P); return s.get_state(),float(inn@Si@inn)
    def update_gps(s,z): return s._upd(z,[0,1,2],s.R_gps)
    def update_radar(s,z): return s._upd(z,[3,4],s.R_radar)

class CKF(BaseKF):
    def _init_(s):
        super()._init_(); s.n=6; s.m=12; s.sn=np.sqrt(6.); s._S=np.linalg.cholesky(s._P)
    def _cp(s):
        pts=np.zeros((12,6))
        for i in range(6): pts[i]=s.state+s.sn*s._S[:,i]; pts[6+i]=s.state-s.sn*s._S[:,i]
        return pts
    def _tri(s,A):
        _,R=qr(A.T,mode='economic'); L=R.T; d=np.diag(L); return L*np.where(d<0,-1.,1.)[None,:]
    def predict(s,ax,ay,az,dt):
        X=s._cp(); Xp=np.array([s._kin(x,ax,ay,az,dt) for x in X])
        s.state=Xp.mean(0); W=(Xp-s.state).T/np.sqrt(s.m)
        SQ=np.linalg.cholesky(s.Q); s._S=s._tri(np.hstack([W,SQ])); s._P=s._S@s._S.T; return s.get_state()
    def _upd(s,z,idx,R):
        X=s._cp(); Z=X[:,idx]; zp=Z.mean(0)
        dZ=(Z-zp).T/np.sqrt(s.m); dX=(X-s.state).T/np.sqrt(s.m)
        SR=np.linalg.cholesky(R); Szz=s._tri(np.hstack([dZ,SR])); Pxz=dX@dZ.T
        tmp=np.linalg.solve(Szz,Pxz.T); K=np.linalg.solve(Szz.T,tmp).T
        inn=z-zp; s.state+=K@inn; s._S=s._tri(np.hstack([dX-K@dZ,K@SR])); s._P=s._S@s._S.T
        Sf=Szz@Szz.T; return s.get_state(),float(inn@np.linalg.solve(Sf,inn))
    def update_gps(s,z): return s._upd(z,[0,1,2],s.R_gps)
    def update_radar(s,z): return s._upd(z,[3,4],s.R_radar)

FILTERS={'EKF':EKF,'UKF':UKF,'CKF':CKF}


