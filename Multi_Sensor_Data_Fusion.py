# CELL 10: Training

EPISODES=200

def set_seeds(seed=42): np.random.seed(seed); random.seed(seed); torch.manual_seed(seed)

def train_agent(FC,AC,aname,episodes=EPISODES,seed=42,spoof_prob=0.):
    set_seeds(seed)
    train_dfs=[df_all[df_all['scene_id']==s].reset_index(drop=True) for s in train_scenes_ids if len(df_all[df_all['scene_id']==s])>5]
    agent=AC(11,ad=3); rets,errs=[],[]
    for ep in range(episodes):
        env=FilterEnv(train_dfs[ep%len(train_dfs)],FC,spoof_prob=spoof_prob)
        s=env.reset(); tr,se=0.,[]
        while True:
            a=agent.act(s); ns,r,done,info=env.step(a)
            if aname=='PPO': agent.store(s,a,r,float(done))
            else: agent.buf.push(s,a,r,ns,float(done)); agent.update()
            tr+=r
            if 'pos_err' in info: se.append(info['pos_err'])
            s=ns
            if done: break
        if aname=='PPO': agent.update()
        rets.append(tr); errs.append(np.mean(se) if se else 0.)
        if aname=='TD3': agent.en=max(.03,agent.en*.995)
        if (ep+1)%50==0: print(f"  {aname} ep {ep+1}/{episodes} ret={np.mean(rets[-50:]):.1f} err={np.mean(errs[-50:]):.3f}m")
    return agent,{'returns':rets,'errors':errs}

def eval_agent(FC,agent,aname,spoof_fn=None):
    res={}
    for sid in sorted(df_all['scene_id'].unique()):
        sd=df_all[df_all['scene_id']==sid].reset_index(drop=True)
        sp=spoof_fn(len(sd),seed=sid) if spoof_fn else None
        env=FilterEnv(sd,FC); env.spoof=sp; s=env.reset()
        ests,errs,verrs,niss,att=[env.filt.get_state()],[0.],[0.],[0.],[False]
        while True:
            a=agent.act(s,ev=True); ns,_,done,info=env.step(a)
            ests.append(env.filt.get_state())
            errs.append(info.get('pos_err',0.)); verrs.append(info.get('vel_err',0.))
            niss.append(info.get('nis',0.)); att.append(info.get('attacked',False))
            s=ns
            if done: break
        res[sid]=dict(estimates=np.array(ests),ground_truth=sd[['gps_x','gps_y','gps_z']].values,
                       errors=np.array(errs),vel_errors=np.array(verrs),nis=np.array(niss),
                       attacked=att,scene_name=sd['scene_name'].iloc[0])
    return res

