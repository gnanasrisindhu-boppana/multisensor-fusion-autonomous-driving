RADAR_CH = ['RADAR_FRONT','RADAR_FRONT_LEFT','RADAR_FRONT_RIGHT','RADAR_BACK_LEFT','RADAR_BACK_RIGHT']

def quat_to_euler(q0,q1,dt):
    r0=Rotation.from_quat([q0[1],q0[2],q0[3],q0[0]]); r1=Rotation.from_quat([q1[1],q1[2],q1[3],q1[0]])
    return (r0.inv()*r1).as_euler('xyz')/dt if dt>0 else np.zeros(3)

def radar_feat(nusc,tok):
    try:
        sd=nusc.get('sample_data',tok); pc=RadarPointCloud.from_file(nusc.dataroot+'/'+sd['filename']); p=pc.points
        if p.shape[1]==0: return {k:0 for k in ['radar_range_mean','radar_range_std','radar_vel_mean','radar_vel_std','radar_rcs_mean','radar_rcs_std','radar_count']}
        rng=np.sqrt(p[0]**2+p[1]**2)
        return dict(radar_range_mean=np.mean(rng),radar_range_std=np.std(rng),radar_vel_mean=np.mean(p[8]),radar_vel_std=np.std(p[8]),radar_rcs_mean=np.mean(p[5]),radar_rcs_std=np.std(p[5]),radar_count=p.shape[1])
    except: return {k:0 for k in ['radar_range_mean','radar_range_std','radar_vel_mean','radar_vel_std','radar_rcs_mean','radar_rcs_std','radar_count']}

def extract_scene(nusc,scene):
    s=nusc.get('sample',scene['first_sample_token']); rows=[]; pe=None; pt=None
    while True:
        sd=nusc.get('sample_data',s['data']['RADAR_FRONT']); ego=nusc.get('ego_pose',sd['ego_pose_token'])
        ts=s['timestamp']/1e6; pos=ego['translation']; q=ego['rotation']
        row=dict(timestamp=ts,scene_name=scene['name'],gps_x=pos[0],gps_y=pos[1],gps_z=pos[2])
        dt=(ts-pt) if pt else 0.5; row['dt']=max(dt,0.01)
        if pe: pp=pe['translation']; row['vx']=(pos[0]-pp[0])/row['dt']; row['vy']=(pos[1]-pp[1])/row['dt']; row['vz']=(pos[2]-pp[2])/row['dt']
        else: row['vx']=row['vy']=row['vz']=0.
        if pe and rows: row['ax']=(row['vx']-rows[-1].get('vx',0))/row['dt']; row['ay']=(row['vy']-rows[-1].get('vy',0))/row['dt']; row['az']=(row['vz']-rows[-1].get('vz',0))/row['dt']
        else: row['ax']=row['ay']=row['az']=0.
        if pe: g=quat_to_euler(pe['rotation'],q,row['dt']); row['gyro_x'],row['gyro_y'],row['gyro_z']=g
        else: row['gyro_x']=row['gyro_y']=row['gyro_z']=0.
        agg={k:[] for k in ['radar_range_mean','radar_range_std','radar_vel_mean','radar_vel_std','radar_rcs_mean','radar_rcs_std','radar_count']}
        for ch in RADAR_CH:
            if ch in s['data']:
                rf=radar_feat(nusc,s['data'][ch])
                for k,v in rf.items(): agg[k].append(v)
        for k in agg: vl=[v for v in agg[k] if v!=0]; row[k]=np.mean(vl) if vl else 0.
        rows.append(row); pe=ego; pt=ts
        if s['next']=='': break
        s=nusc.get('sample',s['next'])
    return pd.DataFrame(rows)

